-- Skema PostgreSQL pusat SMART-TPS.
-- Diambil dari migrasi Django monitor 0001 (issue #11, `manage.py sqlmigrate monitor 0001`),
-- hanya tabel node dan reading, supaya nama dan tipe kolom sama dengan model Django.
-- Dijalankan otomatis sekali, saat volume PostgreSQL masih kosong.

CREATE TABLE "monitor_node" (
    "node_id" varchar(4) NOT NULL PRIMARY KEY,
    "nama" varchar(100) NOT NULL,
    "lokasi" varchar(200) NOT NULL,
    "pos_x" double precision NOT NULL,
    "pos_y" double precision NOT NULL,
    "aktif" boolean NOT NULL
);

CREATE TABLE "monitor_reading" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "seq" integer NOT NULL CHECK ("seq" >= 0),
    "waktu" timestamp with time zone NOT NULL,
    "mq2" double precision NOT NULL,
    "mq3" double precision NOT NULL,
    "mq4" double precision NOT NULL,
    "mq5" double precision NOT NULL,
    "mq6" double precision NOT NULL,
    "mq8" double precision NOT NULL,
    "mq9" double precision NOT NULL,
    "mq135" double precision NOT NULL,
    "mq136" double precision NOT NULL,
    "suhu" double precision NULL,
    "kelembapan" double precision NULL,
    "level" integer NULL,                    -- 0 Normal, 1 Sedang, 2 Tinggi (dari model-ai di Pi)
    "model_ver" varchar(20) NOT NULL DEFAULT '',
    "node_id" varchar(4) NOT NULL,
    CONSTRAINT "uniq_reading_node_seq" UNIQUE ("node_id", "seq")
);

CREATE INDEX "monitor_node_node_id_83b53c75_like" ON "monitor_node" ("node_id" varchar_pattern_ops);
ALTER TABLE "monitor_reading" ADD CONSTRAINT "monitor_reading_node_id_cc5d6ccc_fk_monitor_node_node_id"
    FOREIGN KEY ("node_id") REFERENCES "monitor_node" ("node_id") DEFERRABLE INITIALLY DEFERRED;
CREATE INDEX "monitor_reading_node_id_cc5d6ccc" ON "monitor_reading" ("node_id");
CREATE INDEX "monitor_reading_node_id_cc5d6ccc_like" ON "monitor_reading" ("node_id" varchar_pattern_ops);
CREATE INDEX "monitor_rea_node_id_51cac3_idx" ON "monitor_reading" ("node_id", "waktu");

